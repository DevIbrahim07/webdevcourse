// conditional statements
//  if, else if, else
let age = 23;
if (age > 18) {
  console.log("can vote");
} else if (age == 18) {
  console.log(" just can vote");
} else {
  console.log("cannot vote");
}

// switch case statement
let day = 3;
switch (day) {
  case 1:
    console.log("monday");
    break;
  case 2:
    console.log("tuesday");
    break;
  case 3:
    console.log("wednesday");
    break;
  case 4:
    console.log("thursday");
    break;
  case 5:
    console.log("friday");
    break;
  case 6:
    console.log("saturday");
    break;
  case 7:
    console.log("sunday");
    break;
  default:
    console.log("invalid day");
}
